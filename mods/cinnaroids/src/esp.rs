//! Bounded actor silhouettes with native mask composition and compact HUD labels.
//!
//! Labels are this component's own HUD surface: one plate slot per selected player, centred
//! on a point above the actor that Cinnabar projects every frame from its interpolated
//! position. Each slot remembers what it published, so a callback sends only the bindings
//! that changed and formats nothing for slots that did not.

use crate::state::Preferences;
use mod_api::bindings::cinnabar::{
    extension::player_state::{Actor, ObservedActor},
    world_draw::masks::{Rgba, Style},
};

/// Leaves callback fuel for combat assistance and maximum-size host observations.
/// The HUD surface has one label slot per player.
pub const MAX_PLAYERS: usize = 6;
/// The HUD layer holding the label slots, generated by `scripts/generate-panel.py`.
pub const SURFACE: &str = include_str!("../ui/hud.json");
/// Plate size in thousandths of a GUI unit: 6-unit glyph columns and 10-unit lines at the
/// earlier host labels' 1.2 scale, plus 2-unit padding on each side.
const COLUMN_MILLI: i64 = 7_200;
const LINE_MILLI: i64 = 12_000;
const PADDING_MILLI: i64 = 4_800;
/// Blocks above the actor's bounds where its label centres.
const LABEL_RISE: f32 = 0.65;
/// Labels that take a new name per callback; the rest show on the following frames, keeping a
/// crowd arriving at once within callback fuel.
const NAMES_PER_FRAME: usize = 3;
pub const MAX_RANGE: f32 = 128.;
pub const COLOR_NAMES: &[&str] = &["Coral", "Pink", "Cyan", "White"];
const COLORS: [[f32; 4]; 4] = [
    [1., 0.5412, 0.3961, 1.],
    [1., 0.12, 0.55, 1.],
    [0.2, 0.85, 1., 1.],
    [0.95, 0.95, 0.95, 1.],
];
/// One callback's selected actor identities and the HUD surface update for their labels.
#[derive(Default)]
pub struct Output {
    pub players: Vec<u64>,
    /// `hud.update-surface` JSON with the `binding_changes` of every slot that changed; none
    /// when no slot did. Cinnabar publishes each slot's `#esp_<index>_at_visible`, false while
    /// its actor is absent or its point is off-screen or behind the camera.
    pub labels: Option<String>,
    /// Whether a label took a new name this frame, the costliest label change.
    pub named: bool,
}

/// What one label slot last published.
#[derive(Default)]
struct Slot {
    shown: bool,
    actor: u64,
    /// Label point relative to the actor's feet, in milliblocks.
    offset: [i64; 3],
    /// The observed name as received and with control characters removed.
    name: String,
    clean: String,
    lines: [String; 2],
    /// Plate size in glyph columns and lines.
    size: (usize, usize),
}

/// The label slots as the HUD surface holds them; reset whenever the surface is set again.
#[derive(Default)]
pub struct Labels {
    slots: [Slot; MAX_PLAYERS],
    /// Distance and health line, reused between labels.
    detail: String,
    json: String,
    /// New names taken this callback.
    named: usize,
    next_slot: usize,
    next_actor: usize,
}

/// A selected player's label inputs.
struct Label<'a> {
    actor: u64,
    offset: [i64; 3],
    name: &'a str,
    distance: Option<i32>,
    health: Option<(i32, Option<i32>)>,
}

impl Labels {
    /// Forgets what the slots hold, for a surface that was set again or removed.
    pub fn reset(&mut self) {
        *self = Self::default();
    }

    /// Selects current-session remote players and returns the bindings that changed since the
    /// last update; absent bounds and health stay unknown.
    #[cfg(test)]
    pub fn update(
        &mut self,
        p: &Preferences,
        session: u64,
        dimension: i32,
        eye: [f32; 3],
        actors: &[ObservedActor],
    ) -> Output {
        self.update_budgeted(p, session, dimension, eye, actors, |_| true)
    }

    /// Rotates deferred actor checks and label writes. `allows(true)` budgets actor work;
    /// `allows(false)` budgets one label write.
    pub fn update_budgeted(
        &mut self,
        p: &Preferences,
        session: u64,
        dimension: i32,
        eye: [f32; 3],
        actors: &[ObservedActor],
        mut allows: impl FnMut(bool) -> bool,
    ) -> Output {
        let mut players = Vec::with_capacity(MAX_PLAYERS);
        let mut labels: [Option<Label>; MAX_PLAYERS] = Default::default();
        let mut shown = 0;
        let count = actors.len().min(MAX_PLAYERS);
        let mut deferred = Vec::new();
        let first = self.next_actor;
        for offset in 0..count {
            let index = (first + offset) % count;
            let observed = &actors[index];
            let actor = &observed.actor;
            if !actor.player
                || actor.session != session
                || actor.dimension != dimension
                || actor.runtime_id == 0
            {
                continue;
            }
            if players.len() == MAX_PLAYERS {
                break;
            }
            let position = [actor.position.0, actor.position.1, actor.position.2];
            if !eye.iter().chain(&position).all(|n| n.is_finite()) {
                continue;
            }
            let distance = position
                .iter()
                .zip(eye)
                .map(|(a, b)| (a - b).powi(2))
                .sum::<f32>()
                .sqrt();
            if distance > f32::from(p.esp_range) {
                continue;
            }
            if !allows(true) {
                if !actor.boxes.is_empty() {
                    deferred.push(actor.runtime_id);
                    if self
                        .slots
                        .iter()
                        .any(|slot| slot.shown && slot.actor == actor.runtime_id)
                    {
                        players.push(actor.runtime_id);
                    }
                }
                continue;
            }
            self.next_actor = (index + 1) % count;
            let Some((min, max)) = bounds(actor) else {
                continue;
            };
            // Exclude the camera actor, including giant/custom actor bounds.
            if (0..3).all(|i| eye[i] >= min[i] && eye[i] <= max[i]) {
                continue;
            }
            players.push(actor.runtime_id);
            let health = actor
                .health
                .filter(|n| n.is_finite() && *n >= 0.)
                .filter(|_| p.esp_health)
                .map(|health| {
                    let maximum = observed.max_health.filter(|n| n.is_finite() && *n > 0.);
                    (ceil(health), maximum.map(ceil))
                });
            let name = if p.esp_names { actor.name.as_str() } else { "" };
            if name.is_empty() && !p.esp_distance && health.is_none() {
                continue;
            }
            // The label centres above the bounds; the host follows the actor's feet.
            let point = [
                (min[0] + max[0]) * 0.5,
                max[1] + LABEL_RISE,
                (min[2] + max[2]) * 0.5,
            ];
            labels[shown] = Some(Label {
                actor: actor.runtime_id,
                offset: std::array::from_fn(|i| milli(point[i] - position[i])),
                name,
                distance: p.esp_distance.then(|| distance.round() as i32),
                health,
            });
            shown += 1;
        }
        // A player keeps its slot while shown, so moving players change no names.
        let preserved: [bool; MAX_PLAYERS] =
            std::array::from_fn(|slot| deferred.contains(&self.slots[slot].actor));
        let mut assigned: [Option<usize>; MAX_PLAYERS] = [None; MAX_PLAYERS];
        let mut placed = [false; MAX_PLAYERS];
        for (index, label) in labels.iter().enumerate() {
            let Some(label) = label else { break };
            if let Some(slot) = (0..MAX_PLAYERS).find(|&slot| {
                assigned[slot].is_none()
                    && !preserved[slot]
                    && self.slots[slot].shown
                    && self.slots[slot].actor == label.actor
            }) {
                assigned[slot] = Some(index);
                placed[index] = true;
            }
        }
        for (index, label) in labels.iter().enumerate() {
            let Some(label) = label.as_ref().filter(|_| !placed[index]) else {
                continue;
            };
            // Prefer a slot that last showed this actor, then a hidden one.
            let free = |slot: &usize| assigned[*slot].is_none() && !preserved[*slot];
            let slot = (0..MAX_PLAYERS)
                .filter(free)
                .find(|&slot| self.slots[slot].actor == label.actor)
                .or_else(|| {
                    (0..MAX_PLAYERS)
                        .filter(free)
                        .find(|&slot| !self.slots[slot].shown)
                })
                .or_else(|| (0..MAX_PLAYERS).find(free))
                .expect("a slot per label");
            assigned[slot] = Some(index);
        }
        self.json.clear();
        self.named = 0;
        let first = self.next_slot;
        for offset in 0..MAX_PLAYERS {
            let slot = (first + offset) % MAX_PLAYERS;
            if preserved[slot] {
                continue;
            }
            let label = assigned[slot].and_then(|index| labels[index].as_ref());
            if label.is_none() || allows(false) {
                self.write(slot, label);
                self.next_slot = (slot + 1) % MAX_PLAYERS;
            } else if label.is_some_and(|label| self.slots[slot].actor != label.actor) {
                self.write(slot, None);
            }
        }
        let labels = (!self.json.is_empty()).then(|| {
            let mut update = String::with_capacity(self.json.len() + 24);
            update.push_str("{\"binding_changes\":{");
            update.push_str(&self.json[1..]);
            update.push_str("}}");
            update
        });
        Output {
            players,
            labels,
            named: self.named > 0,
        }
    }

    /// Appends the bindings of slot `index` that differ from what it last published.
    fn write(&mut self, index: usize, label: Option<&Label>) {
        let Self {
            slots,
            detail,
            json,
            named,
            ..
        } = self;
        let slot = &mut slots[index];
        let digit = char::from(b'0' + index as u8);
        let name = |json: &mut String, suffix: &str| {
            json.push_str(",\"#esp_");
            json.push(digit);
            json.push_str(suffix);
            json.push_str("\":");
        };
        let hide = |slot: &mut Slot, json: &mut String| {
            if std::mem::take(&mut slot.shown) {
                name(json, "_shown");
                json.push_str("false");
            }
        };
        let Some(label) = label else {
            hide(slot, json);
            return;
        };
        if !same(&slot.name, label.name) {
            if *named == NAMES_PER_FRAME {
                hide(slot, json);
                return;
            }
            slot.name.clear();
            slot.name.push_str(label.name);
            clean(&mut slot.clean, label.name);
            *named += usize::from(!slot.clean.is_empty());
        }
        detail.clear();
        if let Some(distance) = label.distance {
            integer(detail, distance);
            detail.push_str(" blocks");
        }
        if let Some((health, maximum)) = label.health {
            if !detail.is_empty() {
                detail.push_str(" · ");
            }
            integer(detail, health);
            if let Some(maximum) = maximum {
                detail.push('/');
                integer(detail, maximum);
            }
            detail.push_str(" HP");
        }
        if slot.clean.is_empty() && detail.is_empty() {
            hide(slot, json);
            return;
        }
        // A name leads with distance and health beneath it; otherwise they lead alone.
        let lines = if slot.clean.is_empty() {
            [detail.as_str(), ""]
        } else {
            [slot.clean.as_str(), detail.as_str()]
        };
        let mut resized = false;
        for (line, (published, next)) in slot.lines.iter_mut().zip(lines).enumerate() {
            if !same(published, next) {
                published.clear();
                published.push_str(next);
                name(json, if line == 0 { "_line1" } else { "_line2" });
                // Names are untrusted server text, so always use JSON string escaping.
                quoted(json, next);
                resized = true;
            }
        }
        if resized {
            let [first, second] = &slot.lines;
            let size = (
                columns(first).max(columns(second)),
                usize::from(!first.is_empty()) + usize::from(!second.is_empty()),
            );
            if size.0 != slot.size.0 {
                name(json, "_w");
                decimal(json, size.0 as i64 * COLUMN_MILLI + PADDING_MILLI);
            }
            if size.1 != slot.size.1 {
                name(json, "_h");
                decimal(json, size.1 as i64 * LINE_MILLI + PADDING_MILLI);
            }
            slot.size = size;
        }
        if slot.actor != label.actor || slot.offset != label.offset {
            slot.actor = label.actor;
            slot.offset = label.offset;
            name(json, "_at");
            json.push_str("{\"project\":{\"actor\":");
            unsigned(json, label.actor);
            json.push_str(",\"offset\":[");
            for (axis, value) in label.offset.iter().enumerate() {
                if axis > 0 {
                    json.push(',');
                }
                decimal(json, *value);
            }
            json.push_str("]}}");
        }
        if !std::mem::replace(&mut slot.shown, true) {
            name(json, "_shown");
            json.push_str("true");
        }
    }
}

/// Copies `name` without control characters, which surface text cannot hold.
fn clean(out: &mut String, name: &str) {
    out.clear();
    if controls(name) {
        out.extend(name.chars().filter(|c| !c.is_control()));
    } else {
        out.push_str(name);
    }
}

// Wasm has no vector instructions and fuel counts every operator, so a byte loop costs tens of
// fuel per byte; these checks look at eight bytes per step instead.
const ONES: u64 = u64::from_ne_bytes([0x01; 8]);
const HIGH: u64 = u64::from_ne_bytes([0x80; 8]);

/// Eight bytes as one word.
fn word(chunk: &[u8; 8]) -> u64 {
    u64::from_ne_bytes(*chunk)
}

/// Whether any byte of `x` is below `n`, which is at most 0x80.
fn below(x: u64, n: u8) -> bool {
    x.wrapping_sub(ONES * u64::from(n)) & !x & HIGH != 0
}

/// Whether any byte of `x` equals `byte`.
fn has(x: u64, byte: u8) -> bool {
    below(x ^ (ONES * u64::from(byte)), 1)
}

/// Whether any eight-byte word, or any remaining byte, matches.
fn any(text: &str, word_matches: impl Fn(u64) -> bool, byte_matches: impl Fn(u8) -> bool) -> bool {
    let (words, rest) = text.as_bytes().as_chunks::<8>();
    words.iter().any(|chunk| word_matches(word(chunk)))
        || rest.iter().any(|&byte| byte_matches(byte))
}

/// Whether text holds a control character: C0, DEL, or C1, which UTF-8 leads with 0xc2.
fn controls(text: &str) -> bool {
    any(
        text,
        |x| below(x, 0x20) || has(x, 0x7f) || has(x, 0xc2),
        |byte| byte < 0x20 || byte == 0x7f || byte == 0xc2,
    ) && text.chars().any(char::is_control)
}

/// Whether JSON needs any of the text's bytes escaped.
fn escapes(text: &str) -> bool {
    any(
        text,
        |x| below(x, 0x20) || has(x, b'"') || has(x, b'\\'),
        |byte| byte < 0x20 || byte == b'"' || byte == b'\\',
    )
}

/// Glyph columns of one label line: its characters, which are its bytes less UTF-8
/// continuation bytes.
fn columns(line: &str) -> usize {
    let (words, rest) = line.as_bytes().as_chunks::<8>();
    let continuations = words
        .iter()
        .map(|chunk| {
            let x = word(chunk);
            // Continuation bytes are 0b10xx_xxxx: the high bit set and the next clear.
            (x & !(x << 1) & HIGH).count_ones() as usize
        })
        .sum::<usize>()
        + rest.iter().filter(|&&byte| byte & 0xc0 == 0x80).count();
    line.len() - continuations
}

/// Whether two strings hold the same bytes, compared eight at a time.
fn same(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let ((left, left_rest), (right, right_rest)) = (a.as_chunks::<8>(), b.as_chunks::<8>());
    left.iter().zip(right).all(|(x, y)| word(x) == word(y)) && left_rest == right_rest
}

/// Rounds a finite value to thousandths.
fn milli(value: f32) -> i64 {
    (f64::from(value) * 1000.).round() as i64
}

/// Rounds a finite, non-negative health value up to a whole point.
fn ceil(value: f32) -> i32 {
    value.ceil().min(i32::MAX as f32) as i32
}

/// Unions valid native hit boxes without fabricating standing dimensions.
fn bounds(actor: &Actor) -> Option<([f32; 3], [f32; 3])> {
    let mut lo = [f32::INFINITY; 3];
    let mut hi = [f32::NEG_INFINITY; 3];
    for b in actor.boxes.iter().take(mod_api::MAX_OBSERVED_ACTOR_BOXES) {
        let min = [b.min.0, b.min.1, b.min.2];
        let max = [b.max.0, b.max.1, b.max.2];
        if !(0..3).all(|i| {
            min[i].is_finite()
                && max[i].is_finite()
                && min[i] <= max[i]
                && min[i].abs().max(max[i].abs()) <= mod_api::MAX_PRIMITIVE_COORDINATE
        }) {
            continue;
        }
        // Finite values compare directly; `f32::min` would add NaN handling per axis.
        for i in 0..3 {
            if min[i] < lo[i] {
                lo[i] = min[i];
            }
            if max[i] > hi[i] {
                hi[i] = max[i];
            }
        }
    }
    (0..3).all(|i| lo[i] < hi[i]).then_some((lo, hi))
}

/// A sharp physical-pixel edge and a restrained halo follow the actual animated mesh.
pub fn appearance(color: u8) -> Style {
    let [r, g, b, a] = COLORS[usize::from(color).min(COLORS.len() - 1)];
    Style {
        outline: Rgba { r, g, b, a },
        outline_radius: 1.5,
        glow: Rgba { r, g, b, a: 0.7 },
        glow_radius: 10.,
    }
}

/// Appends integer digits without the general formatter in a fuel-limited callback.
fn integer(text: &mut String, number: i32) {
    if number < 0 {
        text.push('-');
    }
    unsigned(text, u64::from(number.unsigned_abs()));
}

/// Appends the digits of an unsigned value.
fn unsigned(text: &mut String, mut value: u64) {
    let mut digits = [0u8; 20];
    let mut start = digits.len();
    loop {
        start -= 1;
        digits[start] = b'0' + (value % 10) as u8;
        value /= 10;
        if value == 0 {
            break;
        }
    }
    for digit in &digits[start..] {
        text.push(char::from(*digit));
    }
}

/// Appends thousandths as a decimal number without floating point formatting.
fn decimal(text: &mut String, milli: i64) {
    if milli < 0 {
        text.push('-');
    }
    let absolute = milli.unsigned_abs();
    unsigned(text, absolute / 1000);
    text.push('.');
    for divisor in [100, 10, 1] {
        text.push(char::from(b'0' + ((absolute % 1000 / divisor) % 10) as u8));
    }
}

/// Escapes untrusted server text directly into the HUD buffer, retaining UTF-8 slices. Text
/// that needs no escaping is copied whole.
fn quoted(output: &mut String, value: &str) {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    output.push('"');
    if !escapes(value) {
        output.push_str(value);
        output.push('"');
        return;
    }
    let mut start = 0;
    for (index, byte) in value.bytes().enumerate() {
        if byte == b'"' || byte == b'\\' || byte < 0x20 {
            output.push_str(&value[start..index]);
            output.push('\\');
            if byte < 0x20 {
                output.push_str("u00");
                output.push(char::from(HEX[usize::from(byte / 16)]));
                output.push(char::from(HEX[usize::from(byte % 16)]));
            } else {
                output.push(char::from(byte));
            }
            start = index + 1;
        }
    }
    output.push_str(&value[start..]);
    output.push('"');
}

